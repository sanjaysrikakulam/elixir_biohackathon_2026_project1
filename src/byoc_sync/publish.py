"""Turn a plan into branches and pull requests.

Per-user mode (default): every user with a change gets the branch ``<naming.branch>`` (e.g.
``alice01_byoc_ci``), always one bot commit on top of the current base branch, and one pull request. Branches
are regenerated from the base on every run instead of rebased, so a PR never conflicts with another BYOC PR
that was merged meanwhile (the vault is a single encrypted blob). Single mode puts every change on
``byoc_ci_batch`` in one pull request.

For each branch:

* an open pull request is updated in place, never duplicated;
* nothing is pushed when the remote branch already holds exactly this change on the current base;
* if the newest pull request for the branch was closed without merging (rejected) and the request is unchanged
  (same fingerprint), nothing happens unless ``reopen_rejected`` is set, so a scheduled job does not reopen it
  on every run.

Pull requests are never closed by byoc-sync; admins close the ones that are no longer wanted. Failures are
reported per user; a rerun converges.
"""

from __future__ import annotations

import hashlib
import hmac
import json
from dataclasses import dataclass
from typing import Literal

from .config import SiteConfig
from .github import GitHub, PullRequest
from .gitops import GitError, Workspace
from .naming import SINGLE_BRANCH, Names
from .planner import Materialized, Repo, RunPlan, UserPlan, materialize
from .vault import VaultFile

FINGERPRINT_PREFIX = "<!-- byoc-sync fingerprint: "
MAX_BODY = 60000  # GitHub refuses pull request bodies over 65536 characters
TITLES = {
    "create": "Add BYOC Pulsar endpoint {name}",
    "update": "Update BYOC Pulsar endpoint {name}",
    "delete": "Remove BYOC Pulsar endpoint {name}",
    "rename": "Rename BYOC Pulsar endpoint {previous} to {name}",
}


@dataclass
class PublishResult:
    email: str
    name: str | None
    branch: str
    outcome: Literal["opened", "updated", "unchanged", "rejected", "failed", "conflict"]
    url: str | None = None
    detail: str = ""


def fingerprint(user: UserPlan, key: bytes | None) -> str:
    """Identifies a request without its password, so a rejected PR is not reopened for the same data (a new
    password alone does not reopen it). Keyed with ``BYOC_SYNC_FINGERPRINT_KEY`` when available."""
    req = user.request
    data = {"action": user.action, "name": user.name, "email": user.email, "previous": user.previous_name}
    if req is not None:
        data.update(
            max_cores=req.max_cores,
            max_mem=req.max_mem,
            min_gpus=req.min_gpus,
            max_gpus=req.max_gpus,
            nfs_path=req.nfs_path,
        )
    canonical = json.dumps(data, sort_keys=True).encode()
    if key:
        return hmac.new(key, canonical, hashlib.sha256).hexdigest()[:32]
    return hashlib.sha256(canonical).hexdigest()[:32]


def _fingerprint_of(pr: PullRequest) -> str | None:
    start = pr.body.find(FINGERPRINT_PREFIX)
    if start < 0:
        return None
    rest = pr.body[start + len(FINGERPRINT_PREFIX) :]
    return rest.split(" -->", 1)[0].strip()


def _title(user: UserPlan) -> str:
    return TITLES[user.action].format(name=user.name, previous=user.previous_name)


def _describe_user(user: UserPlan) -> list[str]:
    req = user.request
    lines = [f"### {_title(user)}", ""]
    if user.galaxy_id:
        lines.append(f"- Galaxy user id: `{user.galaxy_id}`")
    if req is not None:
        lines.append(f"- Limits: {req.max_cores} cores, {req.max_mem} GB memory, GPUs {req.min_gpus} to {req.max_gpus}")
        lines.append(f"- NFS path: `{req.nfs_path}`" if req.nfs_path else "- NFS path: not set (Pulsar defaults)")
    lines += [f"- {reason}" for reason in user.reasons]
    return lines + [""]


def _describe_files(users: list[UserPlan], result: Materialized, site: SiteConfig) -> list[str]:
    users_file = site.targets["users"].file
    # The users entry is keyed by e-mail; pull request text names the endpoint instead.
    names = {object_id: user.name for user in users for object_id in user.objects.get("users", {})}
    lines = ["### Files", ""]
    for path, file_plan in sorted(result.files.items()):
        for change in file_plan.changes:
            fields = f" ({', '.join(change.fields)})" if change.fields else ""
            what = f"rule for `{names.get(change.object_id)}`" if path == users_file else f"`{change.object_id}`"
            lines.append(f"- `{path}`: {change.action} {what}{fields}")
    for change in result.vault.changes:
        lines.append(f"- `{site.vault_file}`: {change.action} `{change.key}` (encrypted)")
    return lines + [""]


def _body(users: list[UserPlan], result: Materialized, site: SiteConfig, fp: str) -> str:
    intro = [
        'This pull request was generated by byoc-sync from users\' "Bring your own compute" (BYOC Pulsar)',
        "preferences in Galaxy. The branch is regenerated on every run: do not push to it.",
        "",
    ]
    outro = [
        "Before merging:",
        "- [ ] the endpoint owner is known to the admins and the limits are plausible",
        "- [ ] the RabbitMQ user/vhost and the Pulsar runner match the endpoint's Pulsar configuration",
        "",
        f"{FINGERPRINT_PREFIX}{fp} -->",
    ]
    details = [line for user in users for line in _describe_user(user)] + _describe_files(users, result, site)
    body = "\n".join(intro + details + outro)
    if len(body) <= MAX_BODY:
        return body
    # Too long for GitHub (many users in one pull request): one line per user, the diff has the rest.
    summary = [f"- {_title(user)}" for user in users] + [
        "",
        "(Details omitted to fit GitHub's limit; see the diff.)",
        "",
    ]
    return "\n".join(intro + summary + outro)[:MAX_BODY]


class Publisher:
    def __init__(
        self,
        ws: Workspace,
        gh: GitHub,
        site: SiteConfig,
        vault_password: bytes,
        *,
        reopen_rejected: bool,
        fingerprint_key: bytes | None,
    ):
        self.ws, self.gh, self.site = ws, gh, site
        self.vault_password = vault_password
        self.reopen_rejected = reopen_rejected
        self.fingerprint_key = fingerprint_key

    def _materialize(self, users: list[UserPlan]) -> Materialized:
        self.ws.reset()
        repo = Repo(self.ws.path, self.site)
        vault = VaultFile(self.ws.path / self.site.vault_file, self.vault_password)
        return materialize(users, repo, vault)

    def _same_as_remote(self, remote_sha: str, result: Materialized) -> bool:
        """Whether the remote branch already is this change: one commit making exactly these edits, on a base
        that has not changed the files involved since (unrelated merges do not force a new push)."""
        base = self.ws.base_sha()
        parent = self.ws.parent(remote_sha)
        if parent is None:
            return False
        wanted = set(result.files) | ({self.site.vault_file} if result.vault.changed else set())
        try:
            if self.ws.changed_paths(parent, remote_sha) != wanted:
                return False
            if parent != base and self.ws.changed_paths(parent, base) & wanted:
                return False
        except (ValueError, GitError):  # e.g. the parent is missing from a shallow clone: rebuild
            return False
        for path, file_plan in result.files.items():
            if self.ws.show(remote_sha, path) != file_plan.text.encode():
                return False
        if result.vault.changed:
            # Vault ciphertext is salted, so compare what it decrypts to.
            path = self.ws.path / ".byoc-sync-remote-vault"
            try:
                path.write_bytes(self.ws.show(remote_sha, self.site.vault_file) or b"")
                if VaultFile(path, self.vault_password).plaintext != result.vault.plaintext:
                    return False
            finally:
                path.unlink(missing_ok=True)
        return True

    def branch(self, users: list[UserPlan], branch: str, title: str) -> PublishResult:
        first = users[0]
        if len(users) == 1:
            fp = fingerprint(first, self.fingerprint_key)
        else:
            joined = "".join(sorted(fingerprint(u, self.fingerprint_key) for u in users))
            fp = hashlib.sha256(joined.encode()).hexdigest()[:32]
        history = self.gh.prs_for_branch(branch)
        newest = history[0] if history else None
        open_pr = next((pr for pr in history if pr.is_open), None)
        if newest and newest.rejected and _fingerprint_of(newest) == fp and not self.reopen_rejected:
            return PublishResult(
                first.email,
                first.name,
                branch,
                "rejected",
                newest.url,
                "an identical request was closed without merging",
            )
        result = self._materialize(users)
        if result.conflicts:
            detail = "; ".join(r for reasons in result.conflicts.values() for r in reasons)
            return PublishResult(first.email, first.name, branch, "conflict", detail=detail)
        if not result.changed:
            return PublishResult(first.email, first.name, branch, "unchanged", open_pr.url if open_pr else None)

        remote = self.ws.remote_branch_sha(branch)
        pushed = False
        if not remote or not self._same_as_remote(self.ws.fetch_branch(branch), result):
            for path, file_plan in result.files.items():
                with (self.ws.path / path).open("w", encoding="utf-8", newline="") as handle:
                    handle.write(file_plan.text)
            paths = list(result.files)
            if result.vault.changed:
                (self.ws.path / self.site.vault_file).write_bytes(result.vault.ciphertext())
                paths.append(self.site.vault_file)
            self.ws.commit(title + "\n\nGenerated by byoc-sync.", paths)
            self.ws.push(branch, expected=remote)
            pushed = True

        body = _body(users, result, self.site, fp)
        if open_pr:
            if pushed or open_pr.body != body:
                self.gh.update_pr(open_pr.number, title=title, body=body)
            return PublishResult(first.email, first.name, branch, "updated" if pushed else "unchanged", open_pr.url)
        pr = self.gh.create_pr(branch, self.site.base_branch, title, body)
        return PublishResult(first.email, first.name, branch, "opened", pr.url)


def publish(
    run_plan: RunPlan,
    ws: Workspace,
    gh: GitHub,
    site: SiteConfig,
    vault_password: bytes,
    *,
    mode: Literal["per-user", "single"] = "per-user",
    reopen_rejected: bool = False,
    fingerprint_key: bytes | None = None,
) -> list[PublishResult]:
    publisher = Publisher(
        ws, gh, site, vault_password, reopen_rejected=reopen_rejected, fingerprint_key=fingerprint_key
    )
    # E-mail order: deterministic and the same for both sources (API user ids are opaque encoded strings).
    users = sorted(run_plan.publishable(), key=lambda u: u.email)
    if not users:
        return []
    if mode == "single":
        count = len(users)
        title = f"BYOC Pulsar endpoints: {count} change{'s' if count != 1 else ''}"
        try:
            result = publisher.branch(users, SINGLE_BRANCH, title)
        except Exception as exc:  # noqa: BLE001 - reported, the run continues
            result = PublishResult("", None, SINGLE_BRANCH, "failed", detail=str(exc))
        return [PublishResult(u.email, u.name, SINGLE_BRANCH, result.outcome, result.url, result.detail) for u in users]
    results = []
    for user in users:
        branch = Names.for_(user.name, site.naming).branch
        try:
            results.append(publisher.branch([user], branch, _title(user)))
        except Exception as exc:  # noqa: BLE001 - reported per user, the run continues
            results.append(PublishResult(user.email, user.name, branch, "failed", detail=str(exc)))
    return results
